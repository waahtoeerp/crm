"""Write a Mermaid entity diagram of the live database to docs/database.md.

Run from the project root with: uv run --env-file .env.local tools/db_diagram.py
"""

import os
from pathlib import Path

import psycopg

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "database.md"

TYPE_NAMES = {"int4": "integer", "int8": "bigint", "int2": "smallint", "float8": "double"}

COLUMNS_SQL = """
    SELECT table_name, column_name, udt_name, is_nullable = 'NO' AS not_null
    FROM information_schema.columns
    WHERE table_schema = 'public'
    ORDER BY table_name, ordinal_position
"""

PRIMARY_KEYS_SQL = """
    SELECT kcu.table_name, kcu.column_name
    FROM information_schema.table_constraints tc
    JOIN information_schema.key_column_usage kcu
      ON kcu.constraint_name = tc.constraint_name AND kcu.table_schema = tc.table_schema
    WHERE tc.constraint_type = 'PRIMARY KEY' AND tc.table_schema = 'public'
"""

FOREIGN_KEYS_SQL = """
    SELECT kcu.table_name, kcu.column_name, ccu.table_name, ccu.column_name, c.is_nullable = 'NO'
    FROM information_schema.table_constraints tc
    JOIN information_schema.key_column_usage kcu
      ON kcu.constraint_name = tc.constraint_name AND kcu.table_schema = tc.table_schema
    JOIN information_schema.constraint_column_usage ccu
      ON ccu.constraint_name = tc.constraint_name AND ccu.table_schema = tc.table_schema
    JOIN information_schema.columns c
      ON c.table_schema = kcu.table_schema AND c.table_name = kcu.table_name AND c.column_name = kcu.column_name
    WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = 'public'
    ORDER BY kcu.table_name, kcu.column_name
"""


def build_diagram(conn: psycopg.Connection) -> tuple[list[str], int]:
    primary = {(t, c) for t, c in conn.execute(PRIMARY_KEYS_SQL)}
    foreign_rows = conn.execute(FOREIGN_KEYS_SQL).fetchall()
    foreign = {(t, c) for t, c, *_ in foreign_rows}

    lines = ["erDiagram"]
    tables: dict[str, list[str]] = {}
    for table, column, udt, _not_null in conn.execute(COLUMNS_SQL):
        keys = []
        if (table, column) in primary:
            keys.append("PK")
        if (table, column) in foreign:
            keys.append("FK")
        type_name = TYPE_NAMES.get(udt, udt)
        suffix = f" {', '.join(keys)}" if keys else ""
        tables.setdefault(table, []).append(f"        {type_name} {column}{suffix}")

    for table, columns in tables.items():
        lines.append(f"    {table} {{")
        lines.extend(columns)
        lines.append("    }")

    for child, column, parent, _parent_column, child_not_null in foreign_rows:
        child_side = "|{" if child_not_null else "o{"
        lines.append(f"    {parent} ||--{child_side} {child} : {column}")

    return lines, len(foreign_rows)


def main() -> None:
    url = os.environ.get("DATABASE_URL")
    if not url:
        raise SystemExit("DATABASE_URL is not set. Run with --env-file .env.local")

    with psycopg.connect(url) as conn:
        diagram, fk_count = build_diagram(conn)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "# Database\n\n"
        "Generated by `uv run --env-file .env.local tools/db_diagram.py` from the live database. Do not edit by hand.\n\n"
        "```mermaid\n" + "\n".join(diagram) + "\n```\n"
    )
    print(f"Wrote {OUT.relative_to(ROOT)} ({fk_count} foreign keys)")


if __name__ == "__main__":
    main()
