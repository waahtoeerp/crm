"""Write a Mermaid diagram of the Claude setup to docs/ai-setup.md.

Run from the project root with: uv run tools/ai_diagram.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "ai-setup.md"
CLAUDE_CONFIG = Path.home() / ".claude.json"


def node_id(name: str) -> str:
    return "n_" + "".join(ch if ch.isalnum() else "_" for ch in name)


def skills_in(folder: str) -> list[str]:
    base = ROOT / folder
    if not base.is_dir():
        return []
    return sorted(path.parent.name for path in base.glob("*/SKILL.md"))


def mcp_servers() -> list[str]:
    names: set[str] = set()
    project_file = ROOT / ".mcp.json"
    if project_file.exists():
        names |= set(json.loads(project_file.read_text()).get("mcpServers", {}))
    if CLAUDE_CONFIG.exists():
        config = json.loads(CLAUDE_CONFIG.read_text())
        names |= set(config.get("mcpServers", {}))
        project = config.get("projects", {}).get(str(ROOT), {})
        names |= set(project.get("mcpServers", {}))
    return sorted(names)


def skill_sources() -> dict[str, list[str]]:
    lock_file = ROOT / "skills-lock.json"
    if not lock_file.exists():
        return {}
    sources: dict[str, list[str]] = {}
    for name, info in json.loads(lock_file.read_text()).get("skills", {}).items():
        sources.setdefault(info.get("source", "unknown"), []).append(name)
    return sources


def build_diagram() -> list[str]:
    lines = ["flowchart LR"]
    claude = node_id("claude")
    lines.append(f'    {claude}(["Claude Code"])')

    lines.append(f'    {node_id("claude_md")}["CLAUDE.md"] --> {claude}')

    skills = skills_in(".claude/skills")
    if skills:
        lines.append('    subgraph skills ["Skills in .claude/skills"]')
        for skill in skills:
            lines.append(f'        {node_id("skill_" + skill)}["{skill}"] --> {claude}')
        lines.append("    end")

    for source, names in skill_sources().items():
        src = node_id("source_" + source)
        lines.append(f'    {src}[/"{source}"/]')
        for name in names:
            lines.append(f'    {src} --> {node_id("skill_" + name)}')

    for server in mcp_servers():
        lines.append(f'    {node_id("mcp_" + server)}[("MCP: {server}")] --> {claude}')

    return lines


def main() -> None:
    diagram = build_diagram()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "# AI setup\n\n"
        "Generated by `uv run tools/ai_diagram.py`. Do not edit by hand.\n\n"
        "```mermaid\n" + "\n".join(diagram) + "\n```\n"
    )
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
